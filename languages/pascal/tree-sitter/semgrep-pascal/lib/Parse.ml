            trans_kinterface (Run.matcher_token v0),
            Run.opt
              (fun v -> trans_declarations (Run.matcher_token v))
              v1
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

let trans_unit_ ((kind, body) : mt) : CST.unit_ =
  match body with
  | Children v ->
      (match v with
      | Seq [v0; v1; v2; v3; v4; v5] ->
          (
            trans_kunit (Run.matcher_token v0),
            trans_modulename (Run.matcher_token v1),
            Run.trans_token (Run.matcher_token v2),
            Run.repeat
              (fun v ->
                (match v with
                | Alt (0, v) ->
                    `Inte (
                      trans_interface (Run.matcher_token v)
                    )
                | Alt (1, v) ->
                    `Impl (
                      trans_implementation (Run.matcher_token v)
                    )
                | Alt (2, v) ->
                    `Init (
                      trans_initialization (Run.matcher_token v)
                    )
                | Alt (3, v) ->
                    `Fina (
                      trans_finalization (Run.matcher_token v)
                    )
                | _ -> assert false
                )
              )
              v3
            ,
            Run.opt
              (fun v -> trans_kend (Run.matcher_token v))
              v4
            ,
            trans_kenddot (Run.matcher_token v5)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

let trans_root ((kind, body) : mt) : CST.root =
  match body with
  | Children v ->
      (match v with
      | Alt (0, v) ->
          `Opt_choice_prog (
            Run.opt
              (fun v ->
                (match v with
                | Alt (0, v) ->
                    `Prog (
                      trans_program (Run.matcher_token v)
                    )
                | Alt (1, v) ->
                    `Libr (
                      trans_library (Run.matcher_token v)
                    )
                | Alt (2, v) ->
                    `Unit (
                      trans_unit_ (Run.matcher_token v)
                    )
                | Alt (3, v) ->
                    `Defins (
                      trans_definitions (Run.matcher_token v)
                    )
                | _ -> assert false
                )
              )
              v
          )
      | Alt (1, v) ->
          `Pack (
            trans_package (Run.matcher_token v)
          )
      | Alt (2, v) ->
          `Semg_exp (
            trans_semgrep_expression (Run.matcher_token v)
          )
      | Alt (3, v) ->
          `Semg_stmts (
            trans_semgrep_statements (Run.matcher_token v)
          )
      | Alt (4, v) ->
          `Semg_declas (
            trans_semgrep_declarations (Run.matcher_token v)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

(*
   Costly operation that translates a whole tree or subtree.

   The first pass translates it into a generic tree structure suitable
   to guess which node corresponds to each grammar rule.
   The second pass is a translation into a typed tree where each grammar
   node has its own type.

   This function is called:
   - once on the root of the program after removing extras
     (comments and other nodes that occur anywhere independently from
     the grammar);
   - once of each extra node, resulting in its own independent tree of type
     'extra'.
*)
let translate_tree src node trans_x =
  let matched_tree = Run.match_tree children_regexps src node in
  Option.map trans_x matched_tree


let translate_extra src (node : Tree_sitter_output_t.node) : CST.extra option =
  match node.type_ with
  | "space" ->
      (match translate_tree src node trans_space with
      | None -> None
      | Some x -> Some (`Space (Run.get_loc node, x)))
  | "comment" ->
      (match translate_tree src node trans_comment with
      | None -> None
      | Some x -> Some (`Comment (Run.get_loc node, x)))
  | "ppdirective" ->
      (match translate_tree src node trans_ppdirective with
      | None -> None
      | Some x -> Some (`Ppdirective (Run.get_loc node, x)))
  | _ -> None

let translate_root src root_node =
  translate_tree src root_node trans_root

let parse_input_tree input_tree =
  let orig_root_node = Tree_sitter_parsing.root input_tree in
  let src = Tree_sitter_parsing.src input_tree in
  let errors = Run.extract_errors src orig_root_node in
  let opt_program, extras =
     Run.translate
       ~extras
       ~translate_root:(translate_root src)
       ~translate_extra:(translate_extra src)
       orig_root_node
  in
  Parsing_result.create src opt_program extras errors

let string ?src_file contents =
  let input_tree = parse_source_string ?src_file contents in
  parse_input_tree input_tree

let file src_file =
  let input_tree = parse_source_file src_file in
  parse_input_tree input_tree

